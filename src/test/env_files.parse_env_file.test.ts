import { describe, test, assert } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

import { load_env_file, parse_env_file } from '#lib/env_files.ts';
import { fs } from '#lib/fs.ts';
import { create_fs_paths } from '#lib/fs_paths.ts';
import { is_task_error } from '#lib/task_error.ts';
import { paths } from './test_helpers.ts';
import { to_fs_paths_options } from './fs_test_helpers.ts';

/*

`dotenv_parse.json` records dotenv's `parse` output for each input, dotenv being the oracle
`parse_env_file` is held to: named cases, then a seeded sample of a fuzz, half of it inputs
`parse_env_file` accepted when it was recorded. It's generated by a differential run against
dotenv itself, never edited, and can't be regenerated once dotenv isn't installed,
so a new case of `parse_env_file`'s own is a test here, not an entry there.

*/

interface DotenvCase {
	name: string;
	input: string;
	dotenv: Record<string, string>;
}

const { cases } = JSON.parse(
	readFileSync(join(paths.root, 'src/test/fixtures/env_files/dotenv_parse.json'), 'utf8')
) as { oracle: string; cases: Array<DotenvCase> };

// entries in order, so key order counts
const to_entries = (record: Record<string, string>): Array<[string, string]> =>
	Object.entries(record);

// the named cases refused, each with its message; every other named case is accepted
const REFUSED: ReadonlyMap<string, string> = new Map([
	['colon_separator', 'expected `KEY=value`, a comment, or a blank line'],
	['colon_separator_tab', 'expected `KEY=value`, a comment, or a blank line'],
	['colon_joins_next_line', 'expected `KEY=value`, a comment, or a blank line'],
	['bare_key', 'expected `KEY=value`, a comment, or a blank line'],
	['key_then_equals_next_line', 'expected `KEY=value`, a comment, or a blank line'],
	['export_alone_line', 'expected `KEY=value`, a comment, or a blank line'],
	['garbage_line', 'expected `KEY=value`, a comment, or a blank line'],
	['key_with_space', 'expected `KEY=value`, a comment, or a blank line'],
	['no_key', 'expected `KEY=value`, a comment, or a blank line'],
	['non_ascii_key', 'expected `KEY=value`, a comment, or a blank line'],
	['hash_glued', 'a `#` not after whitespace is ambiguous, quote the value or space the comment'],
	[
		'hash_right_after_equals',
		'a `#` not after whitespace is ambiguous, quote the value or space the comment'
	],
	['url_fragment', 'a `#` not after whitespace is ambiguous, quote the value or space the comment'],
	['text_after_closing_quote', 'only a comment may follow the closing "'],
	['two_quoted_strings', 'only a comment may follow the closing "'],
	['unterminated_double', `the value's opening " has no closing one`],
	['unterminated_single', `the value's opening ' has no closing one`],
	['quote_then_unquoted_glued', "only a comment may follow the closing '"],
	[
		'escaped_quote_in_double',
		'a `\\` before the closing " is ambiguous, quote the value another way'
	],
	['escaped_quote_at_end', 'a `\\` before the closing " is ambiguous, quote the value another way'],
	[
		'trailing_backslash_in_single',
		"a `\\` before the closing ' is ambiguous, quote the value another way"
	],
	['quoted_value_on_next_line', 'expected `KEY=value`, a comment, or a blank line'],
	['quoted_value_after_blank_line', 'expected `KEY=value`, a comment, or a blank line'],
	['multiline_text_after_close', 'only a comment may follow the closing "'],
	['proto_key', 'the key `__proto__` is refused'],
	['export_proto_key', 'the key `__proto__` is refused'],
	['line_separator_unquoted', 'U+2028 and U+2029 are refused outside quotes'],
	['line_separator_in_comment', 'U+2028 and U+2029 are refused outside quotes'],
	['paragraph_separator_after_value', 'U+2028 and U+2029 are refused outside quotes']
]);

describe('parse_env_file against the recorded dotenv', () => {
	const named = cases.filter((c) => !c.name.startsWith('fuzz_'));
	const fuzzed = cases.filter((c) => c.name.startsWith('fuzz_'));

	test('every recorded input is refused or read as dotenv reads it', () => {
		const diverged = cases.filter((c) => {
			const parsed = parse_env_file(c.input);
			return (
				parsed.ok &&
				JSON.stringify(to_entries(parsed.value)) !== JSON.stringify(to_entries(c.dotenv))
			);
		});
		assert.deepEqual(
			diverged.map((c) => c.name),
			[]
		);
	});

	test('each named case is accepted, or refused with its message', () => {
		for (const c of named) {
			const parsed = parse_env_file(c.input);
			const refused = REFUSED.get(c.name);
			if (refused === undefined) {
				assert.ok(parsed.ok, `${c.name}: ${parsed.ok ? '' : parsed.message}`);
			} else {
				assert.ok(!parsed.ok, `${c.name} is accepted`);
				assert.strictEqual(parsed.message, refused, c.name);
			}
		}
		assert.includeMembers(
			named.map((c) => c.name),
			[...REFUSED.keys()]
		);
	});

	// a parser refusing its way past the oracle would pass the first test; the recording took
	// exactly half its fuzzed inputs from those accepted, so a new refusal of any fails this,
	// a deliberate narrowing included, which then lowers the threshold by what it refuses
	test('at least half the fuzzed inputs are accepted, as when recorded', () => {
		const accepted = fuzzed.filter((c) => parse_env_file(c.input).ok);
		assert.ok(fuzzed.length > 0);
		assert.ok(accepted.length * 2 >= fuzzed.length, `${accepted.length} of ${fuzzed.length}`);
	});
});

describe('parse_env_file', () => {
	test('reads the forms a project writes', () => {
		const parsed = parse_env_file(
			[
				'# comment',
				'export A=1',
				'B = two words # comment',
				'C="multi',
				'line\\nescape" # comment',
				"D='kept \\n'",
				'E=`back`',
				'F=',
				''
			].join('\r\n')
		);
		assert.ok(parsed.ok);
		assert.deepEqual(to_entries(parsed.value), [
			['A', '1'],
			['B', 'two words'],
			['C', 'multi\nline\nescape'],
			['D', 'kept \\n'],
			['E', 'back'],
			['F', '']
		]);
	});

	test('expands no variable', () => {
		const parsed = parse_env_file('A=1\nB=$A\nC="${A}"\n');
		assert.ok(parsed.ok);
		assert.deepEqual(parsed.value, { A: '1', B: '$A', C: '${A}' });
	});

	test('a later line of a key wins, in the place of its first', () => {
		const parsed = parse_env_file('A=1\nB=2\nA=3\n');
		assert.ok(parsed.ok);
		assert.deepEqual(to_entries(parsed.value), [
			['A', '3'],
			['B', '2']
		]);
	});

	test('a refusal names the line it is on, counting the lines of a quoted value', () => {
		const parsed = parse_env_file('A=1\r\nB="x\ny\nz"\n\nC=a#b\n');
		assert.ok(!parsed.ok);
		assert.strictEqual(parsed.line, 6);
	});

	test('a refused quoted value spanning lines names the line its quote opened on', () => {
		for (const [input, line, message] of [
			['A="unclosed\nB="y"\n', 1, 'only a comment may follow the closing "'],
			['A=1\nB="x\ny" z\n', 2, 'only a comment may follow the closing "'],
			[
				"A=1\nB='x\ny\\'\n",
				2,
				"a `\\` before the closing ' is ambiguous, quote the value another way"
			],
			['A=1\nB=`x\ny`\u2028\n', 2, 'U+2028 and U+2029 are refused outside quotes']
		] as const) {
			const parsed = parse_env_file(input);
			assert.ok(!parsed.ok, JSON.stringify(input));
			assert.strictEqual(parsed.message, message, JSON.stringify(input));
			assert.strictEqual(parsed.line, line, JSON.stringify(input));
		}
	});
	// each quote's own refusal, and the separators around a quoted value, none in the recorded corpus
	test('refuses a `\\` before a closing backtick, and U+2028 and U+2029 around a quoted value', () => {
		for (const [input, message] of [
			['A=`x\\`\n', 'a `\\` before the closing ` is ambiguous, quote the value another way'],
			['A=\u2028"x"\n', 'U+2028 and U+2029 are refused outside quotes'],
			['A="x"\u2029\n', 'U+2028 and U+2029 are refused outside quotes']
		] as const) {
			const parsed = parse_env_file(input);
			assert.ok(!parsed.ok, JSON.stringify(input));
			assert.strictEqual(parsed.message, message, JSON.stringify(input));
			assert.strictEqual(parsed.line, 1, JSON.stringify(input));
		}
	});
});

describe('load_env_file', () => {
	test('throws a `TaskError` naming the path and line of what it refuses', async () => {
		await using temp = await fs.temp_dir();
		const fs_paths = create_fs_paths({ ...fs, project: temp }, to_fs_paths_options());
		await temp.write('.env.bad', 'A=1\nB: 2\n');
		let thrown: unknown;
		try {
			await load_env_file(fs_paths, '.env.bad');
		} catch (error) {
			thrown = error;
		}
		assert.ok(is_task_error(thrown));
		assert.strictEqual(
			thrown.message,
			'Invalid env file .env.bad, line 2: expected `KEY=value`, a comment, or a blank line'
		);
	});
});
