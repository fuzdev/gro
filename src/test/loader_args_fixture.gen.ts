import type { Gen } from '#lib/gen.ts';
import { spawn_with_loader_args } from '#lib/gro_helpers.ts';

/*

Writes the fixture the binary's twin of `spawn_with_loader_args` is held to:
each case's loader path, invoke path, args, and `NODE_ENV`, and the Node args the function
makes of them, which the binary's fallback runs the Node gro with.
The cases are here and the results are the function's, so the fixture is never edited by hand,
and `gro gen --check` fails when the function moves until it's regenerated,
the twin's test then failing where it hasn't followed.

*/

interface LoaderArgsCase {
	name: string;
	loader_path: string;
	invoke_path: string;
	argv: Array<string>;
	node_env: string | null;
}

const CASES: Array<LoaderArgsCase> = [
	{
		name: 'plain',
		loader_path: '/p/node_modules/@fuzdev/gro/dist/loader.js',
		invoke_path: '/p/node_modules/@fuzdev/gro/dist/invoke.js',
		argv: ['check'],
		node_env: null
	},
	{
		name: 'production',
		loader_path: '/p/node_modules/@fuzdev/gro/dist/loader.js',
		invoke_path: '/p/node_modules/@fuzdev/gro/dist/invoke.js',
		argv: ['dev', '--allow-read=.', '--', 'gro', 'gen'],
		node_env: 'production'
	},
	{
		name: 'development',
		loader_path: '/a/loader.js',
		invoke_path: '/a/invoke.js',
		argv: [],
		node_env: 'development'
	},
	{
		name: 'empty_node_env',
		loader_path: '/a/loader.js',
		invoke_path: '/a/invoke.js',
		argv: [],
		node_env: ''
	},
	{
		name: 'path_characters',
		loader_path: '/h/a b/#x?y%z/"q"/it\'s\\/é\u{1f600}/[c]~!$&()*+,;=@:/loader.js',
		invoke_path: '/h/a b/#x?y%z/invoke.js',
		argv: ['', ' ', 'é'],
		node_env: null
	},
	{
		name: 'dots_in_the_loader_path',
		loader_path: '/a/./b/../c//loader.js',
		invoke_path: '/a/c/invoke.js',
		argv: [],
		node_env: null
	}
];

export const gen: Gen = ({ origin_path }) => {
	const names: Set<string> = new Set();
	for (const { name } of CASES) {
		if (names.has(name)) throw Error(`two loader args cases are named ${name}`);
		names.add(name);
	}
	const fixture = {
		description:
			"Each case's loader path, invoke path, args, and `NODE_ENV`, and the Node args " +
			'`spawn_with_loader_args` (`src/lib/gro_helpers.ts`) makes of them. ' +
			`Generated by ${origin_path}, never edited by hand.`,
		cases: CASES.map((c) => ({
			...c,
			args: spawn_with_loader_args(c.loader_path, c.invoke_path, c.argv, c.node_env ?? undefined)
		}))
	};
	return {
		filename: '../../crates/gro_cli/tests/fixtures/verb/loader_args.json',
		content: JSON.stringify(fixture, null, '\t') + '\n'
	};
};
